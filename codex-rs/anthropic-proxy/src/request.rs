use crate::tools::translate_tools;

/// Tool name used to replay legacy `local_shell_call` items.
const LOCAL_SHELL_TOOL_NAME: &str = "local_shell";

/// Text sent when the Messages API needs a user turn that Codex history lacks.
const CONTINUE_TEXT: &str = "Continue.";

/// Thinking budgets for models that predate adaptive thinking.
const BUDGET_MINIMAL: u32 = 1_024;
const BUDGET_LOW: u32 = 2_048;
const BUDGET_MEDIUM: u32 = 8_192;
const BUDGET_HIGH: u32 = 16_384;
const BUDGET_XHIGH: u32 = 32_000;
/// Room left for visible output on top of a thinking budget.
const BUDGET_OUTPUT_HEADROOM: u32 = 4_096;

#[derive(Debug, Clone)]
pub struct TranslateOptions {
    /// `max_tokens` sent to Anthropic (raised when a thinking budget needs it).
    pub max_tokens: u32,
    /// Prompt cache lifetime; `None` sends no `cache_control` at all.
    pub cache_ttl: Option<CacheTtl>,
}

impl Default for TranslateOptions {
    fn default() -> Self {
        Self {
            max_tokens: 64_000,
            cache_ttl: Some(CacheTtl::FiveMinutes),
        }
    }
}

/// Lifetime of the prompt cache entries the proxy asks Anthropic to write.
#[derive(Debug, Clone, Copy, PartialEq, Eq, clap::ValueEnum)]
pub enum CacheTtl {
    /// Anthropic's default: 5 minutes, refreshed by every hit.
    #[value(name = "5m")]
    FiveMinutes,
    /// 1 hour: writes cost 2x instead of 1.25x; pays off for gaps over 5 min.
    #[value(name = "1h")]
    OneHour,
}

impl CacheTtl {
    fn cache_control(self) -> Value {
        match self {
            CacheTtl::FiveMinutes => json!({"type": "ephemeral"}),
            CacheTtl::OneHour => json!({"type": "ephemeral", "ttl": "1h"}),
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TranslateError(pub String);

impl fmt::Display for TranslateError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}

impl std::error::Error for TranslateError {}

/// A translated request plus what the stream translator needs to map tool
/// calls back to Codex items.
#[derive(Debug)]
pub(crate) struct TranslatedRequest {
    pub(crate) body: AnthropicRequest,
    pub(crate) tools: ToolRegistry,
}

#[derive(Debug, Serialize)]
pub(crate) struct AnthropicRequest {
    pub(crate) model: String,
    pub(crate) max_tokens: u32,
    pub(crate) stream: bool,
    #[serde(skip_serializing_if = "Vec::is_empty")]
    pub(crate) system: Vec<Value>,
    pub(crate) messages: Vec<Message>,
    #[serde(skip_serializing_if = "Vec::is_empty")]
    pub(crate) tools: Vec<Value>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub(crate) tool_choice: Option<Value>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub(crate) thinking: Option<Value>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub(crate) output_config: Option<Value>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub(crate) temperature: Option<Value>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub(crate) top_p: Option<Value>,
    /// Top-level automatic caching: Anthropic puts the breakpoint on the last
    /// cacheable block, so each turn writes the prefix the next one reads.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub(crate) cache_control: Option<Value>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "lowercase")]
pub(crate) enum Role {
    User,
    Assistant,
}

#[derive(Debug, Serialize)]
pub(crate) struct Message {
    pub(crate) role: Role,
    pub(crate) content: Vec<Block>,
}

/// A content block. Tool calls keep their original argument text so replayed
/// history matches what Claude generated byte for byte (key order included).
#[derive(Debug)]
pub(crate) enum Block {
    Json(Value),
    ToolUse { id: String, raw: Box<RawValue> },
}

impl Block {
    fn is_tool_result(&self) -> bool {
        matches!(self, Block::Json(value) if value.get("type").and_then(Value::as_str) == Some("tool_result"))
    }

    fn tool_use_id(&self) -> Option<&str> {
        match self {
            Block::ToolUse { id, .. } => Some(id),
            Block::Json(value) if value.get("type").and_then(Value::as_str) == Some("tool_use") => {
                value.get("id").and_then(Value::as_str)
            }
            Block::Json(_) => None,
        }
    }

    fn tool_result_id(&self) -> Option<&str> {
        match self {
            Block::Json(value) if self.is_tool_result() => {
                value.get("tool_use_id").and_then(Value::as_str)
            }
            Block::Json(_) | Block::ToolUse { .. } => None,
        }
    }
}

impl Serialize for Block {
    fn serialize<S: Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        match self {
            Block::Json(value) => value.serialize(serializer),
            Block::ToolUse { raw, .. } => raw.serialize(serializer),
        }
    }
}

pub(crate) fn translate_request(
    request: &Value,
    options: &TranslateOptions,
) -> Result<TranslatedRequest, TranslateError> {
    let model = request
        .get("model")
        .and_then(Value::as_str)
        .filter(|model| !model.is_empty())
        .ok_or_else(|| TranslateError("request is missing `model`".to_string()))?;

    let input: Vec<Value> = match request.get("input") {
        Some(Value::Array(items)) => items.clone(),
        Some(Value::String(text)) => vec![json!({
            "type": "message",
            "role": "user",
            "content": [{"type": "input_text", "text": text}],
        })],
        _ => return Err(TranslateError("request is missing `input`".to_string())),
    };

    let mut declared_tools: Vec<Value> = request
        .get("tools")
        .and_then(Value::as_array)
        .cloned()
        .unwrap_or_default();
    // Responses Lite carries tool declarations as input items.
    for item in &input {
        if item.get("type").and_then(Value::as_str) == Some("additional_tools") {
            declared_tools.extend(
                item.get("tools")
                    .and_then(Value::as_array)
                    .into_iter()
                    .flatten()
                    .cloned(),
            );
        }
    }
    let rules = model_rules(model);
    debug!(model, family = ?rules.family, "applying model rules");
    let mut registry = ToolRegistry::default();
    let mut tools = translate_tools(&declared_tools, &mut registry, rules.web_search_tool);

    let mut builder = MessagesBuilder::default();
    for item in &input {
        builder.push_item(item);
    }
    let (mut system, mut messages) = builder.finish();

    let plan = plan_thinking(&rules, request.get("reasoning"), options.max_tokens);
    let thinks = rules.thinks(plan.thinking.is_some());
    let mut output_config = serde_json::Map::new();
    if let Some(effort) = plan.effort {
        output_config.insert("effort".to_string(), Value::String(effort.to_string()));
    }
    if let Some(format) = output_format(request) {
        output_config.insert("format".to_string(), format);
    }

    let tool_choice = if tools.is_empty() {
        None
    } else {
        let choice = tool_choice(request, &registry, &rules, thinks);
        if let Some(instruction) = &choice.instruction {
            append_user_text(&mut messages, instruction);
        }
        Some(choice.value)
    };

    // Sampling parameters: rejected outright or for non-default values by
    // Claude 4.7+ / 5.x, and incompatible with thinking everywhere.
    let sampling = |key: &str| {
        let value = request.get(key).filter(|value| value.is_number())?;
        if rules.sampling && !thinks {
            Some(value.clone())
        } else {
            debug!(
                param = key,
                "dropping sampling parameter this model rejects"
            );
            None
        }
    };
    let temperature = sampling("temperature");
    let top_p = sampling("top_p");

    let cache_ttl = options.cache_ttl.map(|ttl| request_cache_ttl(request, ttl));
    let cache_control = cache_ttl.map(|ttl| {
        place_stable_breakpoint(&mut system, &mut tools, ttl);
        ttl.cache_control()
    });

    Ok(TranslatedRequest {
        body: AnthropicRequest {
            model: model.to_string(),
            max_tokens: plan.max_tokens,
            stream: true,
            system,
            messages,
            tools,
            tool_choice,
            thinking: plan.thinking,
            output_config: (!output_config.is_empty()).then_some(Value::Object(output_config)),
            temperature,
            top_p,
            cache_control,
        },
        tools: registry,
    })
}

/// Codex asks for long-lived caching with `prompt_cache_options.ttl`
/// (`30m`/`12h`); the longest Anthropic offers is 1 hour.
fn request_cache_ttl(request: &Value, default: CacheTtl) -> CacheTtl {
    let requested = request
        .get("prompt_cache_options")
        .and_then(|options| options.get("ttl"))
        .and_then(Value::as_str);
    match requested {
        Some(ttl) if ttl != "5m" => CacheTtl::OneHour,
        _ => default,
    }
}

/// Puts an explicit breakpoint at the end of the stable prefix (tools, then
/// system), so it stays cached whatever happens later in `messages`. With the
/// automatic breakpoint at the end of the conversation this uses 2 of the 4
/// breakpoints Anthropic allows.
fn place_stable_breakpoint(system: &mut [Value], tools: &mut [Value], ttl: CacheTtl) {
    let target = match system.last_mut() {
        Some(block) => Some(block),
        // Without a system prompt, the last client tool (server tools carry no
        // `input_schema`) ends the stable prefix.
        None => tools
            .iter_mut()
            .rev()
            .find(|tool| tool.get("input_schema").is_some()),
    };
    if let Some(Value::Object(block)) = target {
        block.insert("cache_control".to_string(), ttl.cache_control());
    }
}

/// Appends a text block to the final user message.
fn append_user_text(messages: &mut [Message], text: &str) {
    if let Some(message) = messages
        .last_mut()
        .filter(|message| message.role == Role::User)
        && let Some(block) = text_block(text)
    {
        message.content.push(block);
    }
}

struct ToolChoice {
    value: Value,
    /// Text added to the last user turn when a forced choice became `auto`.
    instruction: Option<String>,
}

/// Maps `tool_choice`. Forced choice (`required` or a named function) is
/// rejected by Fable 5.1+/Opus 5.5/Sonnet 5.5 and by every model while it
/// thinks, so there it becomes `auto` plus an instruction in the prompt.
fn tool_choice(
    request: &Value,
    registry: &ToolRegistry,
    rules: &ModelRules,
    thinks: bool,
) -> ToolChoice {
    let parallel = request
        .get("parallel_tool_calls")
        .and_then(Value::as_bool)
        .unwrap_or(true);
    let forced = match request.get("tool_choice") {
        Some(Value::String(choice)) if choice == "none" => {
            return ToolChoice {
                value: json!({"type": "none"}),
                instruction: None,
            };
        }
        Some(Value::String(choice)) if choice == "required" => Some(None),
        Some(Value::Object(choice)) => choice
            .get("name")
            .and_then(Value::as_str)
            .map(|name| {
                let namespace = choice.get("namespace").and_then(Value::as_str);
                anthropic_tool_name(namespace, name)
            })
            .filter(|name| registry.lookup(name).is_some())
            .map(Some),
        _ => None,
    };
    let mut instruction = None;
    let mut value = match forced {
        None => json!({"type": "auto"}),
        Some(name) if rules.forced_tool_choice && !thinks => match name {
            Some(name) => json!({"type": "tool", "name": name}),
            None => json!({"type": "any"}),
        },
        Some(name) => {
            debug!(
                family = ?rules.family,
                tool = name.as_deref().unwrap_or("<any>"),
                "model rejects forced tool_choice here; sending auto"
            );
            instruction = Some(match name {
                Some(name) => format!("Respond by calling the `{name}` tool."),
                None => "Respond by calling one of the available tools.".to_string(),
            });
            json!({"type": "auto"})
        }
    };
    if !parallel {
        value["disable_parallel_tool_use"] = Value::Bool(true);
    }
    ToolChoice { value, instruction }
}

/// Maps `text.format` (structured output) to `output_config.format`.
fn output_format(request: &Value) -> Option<Value> {
    let format = request.get("text")?.get("format")?;
    if format.get("type").and_then(Value::as_str) != Some("json_schema") {
        return None;
    }
    let schema = format.get("schema")?;
    Some(json!({"type": "json_schema", "schema": schema}))
}

#[derive(Debug, Clone, PartialEq, Eq)]
struct ThinkingPlan {
    thinking: Option<Value>,
    effort: Option<&'static str>,
    max_tokens: u32,
}

/// Maps `reasoning` onto `thinking` + `output_config.effort` for one model.
///
/// - No `reasoning` at all: the model's defaults (no `thinking`, no effort).
/// - Effort `none`: thinking off where omitting `thinking` turns it off;
///   elsewhere the lowest effort, since several models reject
///   `{type: "disabled"}` and the proxy never sends it (nor `budget_tokens`)
///   to an adaptive model.
/// - `reasoning.summary` absent or `none` (Codex omits the field when the user
///   chose `none`): `display: "omitted"`, otherwise `"summarized"`.
fn plan_thinking(rules: &ModelRules, reasoning: Option<&Value>, max_tokens: u32) -> ThinkingPlan {
    let no_thinking = ThinkingPlan {
        thinking: None,
        effort: None,
        max_tokens,
    };
    let Some(reasoning) = reasoning.filter(|reasoning| reasoning.is_object()) else {
        return no_thinking;
    };
    let effort = reasoning.get("effort").and_then(Value::as_str);
    let summarized = reasoning
        .get("summary")
        .and_then(Value::as_str)
        .is_some_and(|summary| summary != "none");
    match rules.thinking {
        Thinking::AdaptiveOnByDefault | Thinking::AdaptiveOffByDefault => {
            let mapped = effort.and_then(|effort| match effort {
                "none" | "minimal" | "low" => Some("low"),
                "medium" => Some("medium"),
                "high" => Some("high"),
                "xhigh" if rules.supports_xhigh => Some("xhigh"),
                "xhigh" | "max" => Some("max"),
                _ => None,
            });
            let thinking =
                if effort == Some("none") && rules.thinking == Thinking::AdaptiveOffByDefault {
                    None
                } else {
                    let display = if summarized { "summarized" } else { "omitted" };
                    Some(json!({"type": "adaptive", "display": display}))
                };
            ThinkingPlan {
                thinking,
                effort: mapped,
                max_tokens,
            }
        }
        Thinking::Budget => {
            let budget = match effort {
                Some("none") => return no_thinking,
                Some("minimal") => BUDGET_MINIMAL,
                Some("low") => BUDGET_LOW,
                Some("high") => BUDGET_HIGH,
                Some("xhigh" | "max") => BUDGET_XHIGH,
                _ => BUDGET_MEDIUM,
            };
            ThinkingPlan {
                thinking: Some(json!({"type": "enabled", "budget_tokens": budget})),
                effort: None,
                max_tokens: max_tokens.max(budget + BUDGET_OUTPUT_HEADROOM),
            }
        }
        Thinking::Unsupported => no_thinking,
    }
}

#[derive(Default)]
struct MessagesBuilder {
    system: Vec<Value>,
    messages: Vec<Message>,
}

impl MessagesBuilder {
    fn push(&mut self, role: Role, block: Block) {
        match self.messages.last_mut() {
            Some(last) if last.role == role => last.content.push(block),
            _ => self.messages.push(Message {
                role,
                content: vec![block],
            }),
        }
    }

    fn push_text(&mut self, role: Role, text: &str) {
        if let Some(block) = text_block(text) {
            self.push(role, block);
        }
    }

    /// Leading developer/system messages become the `system` prompt; later
    /// ones are delivered as user text so the cached prefix stays intact.
    fn push_instructions(&mut self, text: &str) {
        if text.trim().is_empty() {
            return;
        }
        if self.messages.is_empty() {
            self.system.push(json!({"type": "text", "text": text}));
        } else {
            self.push_text(
                Role::User,
                &format!("<developer_message>\n{text}\n</developer_message>"),
            );
        }
    }

    fn push_item(&mut self, item: &Value) {
        let item_type = item.get("type").and_then(Value::as_str).unwrap_or_else(|| {
            if item.get("role").is_some() {
                "message"
            } else {
                ""
            }
        });
        match item_type {
            "message" => self.push_message(item),
            "reasoning" => {
                let blocks = item
                    .get("encrypted_content")
                    .and_then(Value::as_str)
                    .map(decode_blocks)
                    .unwrap_or_default();
                if blocks.is_empty() {
                    debug!("dropping reasoning item without Claude thinking or server tool blocks");
                }
                for block in blocks {
                    self.push(Role::Assistant, Block::Json(block));
                }
            }
            "function_call" => {
                let name = item.get("name").and_then(Value::as_str).unwrap_or_default();
                let namespace = item.get("namespace").and_then(Value::as_str);
                let arguments = item
                    .get("arguments")
                    .and_then(Value::as_str)
                    .unwrap_or_default();
                let call_id = call_id(item);
                self.push(
                    Role::Assistant,
                    tool_use_block(
                        &call_id,
                        &anthropic_tool_name(namespace, name),
                        &object_arguments(arguments),
                    ),
                );
            }
            "custom_tool_call" => {
                let name = item.get("name").and_then(Value::as_str).unwrap_or_default();
                let namespace = item.get("namespace").and_then(Value::as_str);
                let input = item
                    .get("input")
                    .and_then(Value::as_str)
                    .unwrap_or_default();
                let call_id = call_id(item);
                let arguments = json!({CUSTOM_TOOL_INPUT_PROPERTY: input}).to_string();
                self.push(
                    Role::Assistant,
                    tool_use_block(&call_id, &anthropic_tool_name(namespace, name), &arguments),
                );
            }
            "local_shell_call" => {
                let call_id = call_id(item);
                let action = item
                    .get("action")
                    .filter(|action| action.is_object())
                    .cloned()
                    .unwrap_or_else(|| json!({}));
                self.push(
                    Role::Assistant,
                    tool_use_block(&call_id, LOCAL_SHELL_TOOL_NAME, &action.to_string()),
                );
            }
            "function_call_output" | "custom_tool_call_output" => {
                let call_id = call_id(item);
                let mut result = json!({"type": "tool_result", "tool_use_id": call_id});
                if let Some(content) = tool_result_content(item.get("output")) {
                    result["content"] = content;
                }
                self.push(Role::User, Block::Json(result));
            }
            "agent_message" => {
                let author = item
                    .get("author")
                    .and_then(Value::as_str)
                    .unwrap_or("agent");
                let text = item
                    .get("content")
                    .and_then(Value::as_array)
                    .into_iter()
                    .flatten()
                    .filter_map(|part| part.get("text").and_then(Value::as_str))
                    .collect::<Vec<_>>()
                    .join("\n");
                if !text.trim().is_empty() {
                    self.push_text(Role::User, &format!("[message from {author}]\n{text}"));
                }
            }
            // Display-only: the search itself is replayed from the reasoning
            // item that carries its server tool blocks.
            "web_search_call" => debug!("dropping web_search_call (replayed from reasoning)"),
            other => debug!(
                item_type = other,
                "dropping input item with no Anthropic equivalent"
            ),
        }
    }

    fn push_message(&mut self, item: &Value) {
        let role = item.get("role").and_then(Value::as_str).unwrap_or("user");
        let parts: Vec<Value> = match item.get("content") {
            Some(Value::String(text)) => vec![json!({"type": "input_text", "text": text})],
            Some(Value::Array(parts)) => parts.clone(),
            _ => Vec::new(),
        };
        match role {
            "system" | "developer" => {
                for part in &parts {
                    if let Some(text) = part.get("text").and_then(Value::as_str) {
                        self.push_instructions(text);
                    }
                }
            }
            "assistant" => {
                for part in &parts {
                    let text = part
                        .get("text")
                        .or_else(|| part.get("refusal"))
                        .and_then(Value::as_str);
                    match text {
                        Some(text) => self.push_text(Role::Assistant, text),
                        None => debug!("dropping non-text assistant content"),
                    }
                }
            }
            _ => {
                for part in &parts {
                    if let Some(block) = user_content_block(part) {
                        self.push(Role::User, block);
                    }
                }
            }
        }
    }

    fn finish(self) -> (Vec<Value>, Vec<Message>) {
        let mut messages = pair_tool_results(drop_unanswered_server_tool_uses(self.messages));
        if messages
            .first()
            .is_none_or(|message| message.role != Role::User)
        {
            messages.insert(
                0,
                Message {
                    role: Role::User,
                    content: vec![Block::Json(json!({"type": "text", "text": CONTINUE_TEXT}))],
                },
            );
        }
        // Current Claude models reject a trailing assistant turn (prefill).
        if messages
            .last()
            .is_some_and(|message| message.role == Role::Assistant)
        {
            messages.push(Message {
                role: Role::User,
                content: vec![Block::Json(json!({"type": "text", "text": CONTINUE_TEXT}))],
            });
        }
        (self.system, messages)
    }
}

/// A `server_tool_use` must be followed by its result in the same assistant
/// message; drop any whose result was lost (for example a truncated stream).
fn drop_unanswered_server_tool_uses(mut messages: Vec<Message>) -> Vec<Message> {
    for message in &mut messages {
        if message.role != Role::Assistant {
            continue;
        }
        let answered: HashSet<String> = message
            .content
            .iter()
            .filter_map(|block| match block {
                Block::Json(value)
                    if value
                        .get("type")
                        .and_then(Value::as_str)
                        .is_some_and(|kind| kind.ends_with("_tool_result")) =>
                {
                    value
                        .get("tool_use_id")
                        .and_then(Value::as_str)
                        .map(str::to_string)
                }
                _ => None,
            })
            .collect();
        message.content.retain(|block| match block {
            Block::Json(value)
                if value.get("type").and_then(Value::as_str) == Some("server_tool_use") =>
            {
                let id = value.get("id").and_then(Value::as_str).unwrap_or_default();
                let keep = answered.contains(id);
                if !keep {
                    debug!(id, "dropping server_tool_use without a result");
                }
                keep
            }
            _ => true,
        });
    }
    messages.retain(|message| !message.content.is_empty());
    messages
}

/// Anthropic requires every `tool_use` to be answered by a `tool_result` at
/// the start of the next user message, and every `tool_result` to answer a
/// `tool_use` from the previous assistant message.
fn pair_tool_results(messages: Vec<Message>) -> Vec<Message> {
    let mut out: Vec<Message> = Vec::with_capacity(messages.len());
    let mut pending: Vec<String> = Vec::new();
    for message in messages {
        match message.role {
            Role::Assistant => {
                if !pending.is_empty() {
                    out.push(Message {
                        role: Role::User,
                        content: missing_results(&std::mem::take(&mut pending)),
                    });
                }
                pending = message
                    .content
                    .iter()
                    .filter_map(Block::tool_use_id)
                    .map(str::to_string)
                    .collect();
                out.push(message);
            }
            Role::User => {
                let mut answered: HashSet<String> = HashSet::new();
                let mut results = Vec::new();
                let mut others = Vec::new();
                for block in message.content {
                    match block.tool_result_id() {
                        Some(id)
                            if pending.iter().any(|pending| pending == id)
                                && !answered.contains(id) =>
                        {
                            answered.insert(id.to_string());
                            results.push(block);
                        }
                        Some(id) => {
                            debug!(tool_use_id = id, "converting unmatched tool result to text");
                            if let Some(text) = orphan_result_text(&block) {
                                others.push(text);
                            }
                        }
                        None => others.push(block),
                    }
                }
                let missing: Vec<String> = pending
                    .iter()
                    .filter(|id| !answered.contains(*id))
                    .cloned()
                    .collect();
                pending.clear();
                results.extend(missing_results(&missing));
                results.extend(others);
                if !results.is_empty() {
                    out.push(Message {
                        role: Role::User,
                        content: results,
                    });
                }
            }
        }
    }
    if !pending.is_empty() {
        out.push(Message {
            role: Role::User,
            content: missing_results(&pending),
        });
    }
    out
}

fn missing_results(ids: &[String]) -> Vec<Block> {
    ids.iter()
        .map(|id| {
            Block::Json(json!({
                "type": "tool_result",
                "tool_use_id": id,
                "is_error": true,
                "content": "No output was recorded for this tool call.",
            }))
        })
        .collect()
}

fn orphan_result_text(block: &Block) -> Option<Block> {
    let Block::Json(value) = block else {
        return None;
    };
    let id = value
        .get("tool_use_id")
        .and_then(Value::as_str)
        .unwrap_or_default();
    let content = match value.get("content") {
        Some(Value::String(text)) => text.clone(),
        Some(Value::Array(parts)) => parts
            .iter()
            .filter_map(|part| part.get("text").and_then(Value::as_str))
            .collect::<Vec<_>>()
            .join("\n"),
        _ => String::new(),
    };
    text_block(&format!("Tool output for call {id}:\n{content}"))
}

fn text_block(text: &str) -> Option<Block> {
    // The Messages API rejects empty and whitespace-only text blocks.
    (!text.trim().is_empty()).then(|| Block::Json(json!({"type": "text", "text": text})))
}

fn tool_use_block(id: &str, name: &str, arguments: &str) -> Block {
    let raw = format!(
        "{{\"type\":\"tool_use\",\"id\":{},\"name\":{},\"input\":{arguments}}}",
        Value::String(id.to_string()),
        Value::String(name.to_string()),
    );
    match RawValue::from_string(raw) {
        Ok(raw) => Block::ToolUse {
            id: id.to_string(),
            raw,
        },
        Err(err) => {
            // Callers pass validated JSON object text; keep the call anyway.
            debug!("tool arguments were not valid JSON: {err}");
            Block::Json(json!({"type": "tool_use", "id": id, "name": name, "input": {}}))
        }
    }
}

/// Returns tool arguments as JSON object text, keeping the original text when
/// it already is an object so replayed calls match the model's output.
fn object_arguments(arguments: &str) -> String {
    if arguments.trim().is_empty() {
        return "{}".to_string();
    }
    match serde_json::from_str::<Value>(arguments) {
        Ok(Value::Object(_)) => arguments.to_string(),
        Ok(other) => json!({"value": other}).to_string(),
        Err(_) => json!({"raw_arguments": arguments}).to_string(),
    }
}

fn call_id(item: &Value) -> String {
    let raw = item
        .get("call_id")
        .or_else(|| item.get("id"))
        .and_then(Value::as_str)
        .unwrap_or_default();
    // Anthropic tool ids must match ^[a-zA-Z0-9_-]+$.
    let sanitized: String = raw
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || c == '_' || c == '-' {
                c
            } else {
                '_'
            }
        })
        .collect();
    if sanitized.is_empty() {
        "call_missing_id".to_string()
    } else {
        sanitized
    }
}

fn user_content_block(part: &Value) -> Option<Block> {
    match part
        .get("type")
        .and_then(Value::as_str)
        .unwrap_or("input_text")
    {
        "input_text" | "output_text" | "text" => {
            text_block(part.get("text").and_then(Value::as_str).unwrap_or_default())
        }
        "input_image" => image_block(part).map(Block::Json),
        other => {
            debug!(
                content_type = other,
                "replacing unsupported content with a placeholder"
            );
            text_block(&format!("[{other} content omitted]"))
        }
    }
}

fn image_block(part: &Value) -> Option<Value> {
    let Some(url) = part.get("image_url").and_then(Value::as_str) else {
        let file_id = part
            .get("file_id")
            .and_then(Value::as_str)
            .unwrap_or("unknown");
        return Some(json!({"type": "text", "text": format!("[image file {file_id} omitted]")}));
    };
    if let Some(rest) = url.strip_prefix("data:")
        && let Some((meta, data)) = rest.split_once(',')
        && let Some(media_type) = meta.strip_suffix(";base64")
    {
        return Some(json!({
            "type": "image",
            "source": {"type": "base64", "media_type": media_type, "data": data},
        }));
    }
    if url.starts_with("https://") || url.starts_with("http://") {
        return Some(json!({"type": "image", "source": {"type": "url", "url": url}}));
    }
    debug!("dropping image with an unsupported URL scheme");
    None
}

fn tool_result_content(output: Option<&Value>) -> Option<Value> {
    match output? {
        Value::String(text) if text.is_empty() => None,
        Value::String(text) => Some(Value::String(text.clone())),
        Value::Array(parts) => {
            let blocks: Vec<Value> = parts
                .iter()
                .filter_map(|part| match part.get("type").and_then(Value::as_str) {
                    Some("input_text" | "output_text" | "text") => part
                        .get("text")
                        .and_then(Value::as_str)
                        .filter(|text| !text.trim().is_empty())
                        .map(|text| json!({"type": "text", "text": text})),
                    Some("input_image") => image_block(part),
                    other => {
                        debug!(content_type = ?other, "dropping unsupported tool output content");
                        None
                    }
                })
                .collect();
            (!blocks.is_empty()).then_some(Value::Array(blocks))
        }
        other => Some(Value::String(other.to_string())),
    }
}

